#!/usr/bin/env python3
"""Generate deterministic, synthetic PostgreSQL seed SQL; standard library only."""
import argparse
import base64
import hashlib
import random
from datetime import date, datetime, time, timedelta, timezone
from decimal import Decimal
from pathlib import Path

TZ = timezone(timedelta(hours=7))


def at(day, hour=9):
    return datetime.combine(day, time(hour), TZ)


def build_dataset(customers=60, days=30, end_date=date(2026, 11, 24), seed=42):
    if customers < 50 or days < 30:
        raise ValueError('Cần ít nhất 50 khách hàng và 30 ngày.')
    rng = random.Random(seed)
    start = end_date - timedelta(days=days - 1)
    data = {'customers': [], 'orders': [], 'ai_results': []}
    for cid in range(1, customers + 1):
        # First six customers are stable fixtures; others cover both comparison periods.
        signup_day = start - timedelta(days=days) if cid <= 6 else (
            start + timedelta(days=rng.randrange(-days, days)))
        data['customers'].append({
            'id': cid, 'customer_code': f'SYN-{cid:05d}', 'name': f'Khách giả lập {cid:03d}',
            'country': rng.choice(['VN', 'KR', 'JP', 'SG', 'US']),
            'signup_method': rng.choice(['EMAIL', 'GOOGLE', 'MICROSOFT']),
            'signed_up_at': at(signup_day, 8),
        })

    def order(cid, day, status, amount='199000.00', refund_day=None):
        data['orders'].append({
            'id': len(data['orders']) + 1, 'customer_id': cid,
            'package_name': rng.choice(['STARTER', 'PRO', 'BUSINESS']),
            'amount': Decimal(amount), 'status': status, 'created_at': at(day, 9),
            'paid_at': at(day, 10) if status in ('PAID', 'REFUNDED') else None,
            'refunded_at': at(refund_day, 11) if refund_day else None,
        })

    order(1, start - timedelta(days=2), 'PAID')
    order(1, start + timedelta(days=3), 'PAID')  # Repeat customer, two orders in period.
    order(1, start + timedelta(days=22), 'PAID')
    order(2, start + timedelta(days=20), 'PAID')  # First valid payment in period.
    order(3, start + timedelta(days=15), 'REFUNDED', refund_day=start + timedelta(days=18))
    order(4, start + timedelta(days=7), 'FAILED')
    order(5, start + timedelta(days=8), 'PENDING')
    # Customer 6 deliberately has no orders. Last day and every seventh day have zero revenue.
    for customer in data['customers'][6:]:
        eligible = [start + timedelta(days=i) for i in range(days - 1)
                    if i % 7 != 6 and at(start + timedelta(days=i), 9) >= customer['signed_up_at']]
        if not eligible:
            continue
        for _ in range(rng.randrange(4)):
            day = rng.choice(eligible)
            status = rng.choice(['PAID', 'PAID', 'PAID', 'PENDING', 'FAILED', 'REFUNDED'])
            refund_day = min(day + timedelta(days=rng.randint(1, 3)), end_date) if status == 'REFUNDED' else None
            order(customer['id'], day, status, str(rng.choice([99000, 199000, 499000])), refund_day)

    for customer in data['customers']:
        earliest = max(start, customer['signed_up_at'].date())
        for _ in range(rng.randint(1, 5)):
            day = earliest + timedelta(days=rng.randrange((end_date - earliest).days + 1))
            data['ai_results'].append({
                'id': len(data['ai_results']) + 1, 'customer_id': customer['id'],
                'type': rng.choice(['QUOTE', 'WEBSITE']), 'created_at': at(day, 14),
            })
    # Explicit boundary records at both ends of the requested day range.
    for day, kind in [(start, 'QUOTE'), (end_date, 'WEBSITE')]:
        data['ai_results'].append({'id': len(data['ai_results']) + 1, 'customer_id': 6,
                                   'type': kind, 'created_at': at(day, 14)})
    return data


def sql_value(value):
    if value is None:
        return 'NULL'
    if isinstance(value, (int, Decimal)):
        return str(value)
    if isinstance(value, datetime):
        value = value.isoformat()
    return "'" + str(value).replace("'", "''") + "'"


def insert(table, row):
    return f"INSERT INTO {table} ({', '.join(row)}) VALUES ({', '.join(map(sql_value, row.values()))});"


def render_sql(data):
    lines = [
        '-- Synthetic demo data only. Currency convention: VND; timestamps: UTC+07:00.',
        '-- Generated by scripts/generate_seed.py. Do not load into a populated database.',
        'BEGIN;',
        "SET LOCAL TIME ZONE 'Asia/Ho_Chi_Minh';",
        "DO $$ BEGIN IF EXISTS (SELECT 1 FROM customers) OR EXISTS (SELECT 1 FROM members) "
        "OR EXISTS (SELECT 1 FROM orders) OR EXISTS (SELECT 1 FROM ai_results) "
        "OR EXISTS (SELECT 1 FROM order_status_histories) THEN "
        "RAISE EXCEPTION 'Seed requires empty tables; no data was changed'; END IF; END $$;",
    ]
    member_time = min(c['signed_up_at'] for c in data['customers']) - timedelta(days=1)
    for mid, role in enumerate(['ADMIN', 'OPERATOR', 'VIEWER'], 1):
        salt = f'genie-demo-salt-{mid}'
        digest = base64.b64encode(hashlib.pbkdf2_hmac(
            'sha256', b'DemoOnly!2026', salt.encode(), 600000)).decode()
        lines.append(insert('members', {
            'id': mid, 'email': f'{role.lower()}@example.invalid',
            'password_hash': f'pbkdf2_sha256$600000${salt}${digest}',
            'name': f'Demo {role}', 'role': role, 'created_at': member_time,
        }))
    lines.extend(insert('customers', row) for row in data['customers'])
    lines.extend(["SET LOCAL app.member_id = '2';", "SET LOCAL app.change_reason = 'Synthetic seed transition';"])
    for row in data['orders']:
        initial = dict(row, status='PENDING', paid_at=None, refunded_at=None)
        lines.append(insert('orders', initial))
        oid = row['id']
        if row['status'] in ('PAID', 'REFUNDED'):
            lines.append(f"UPDATE orders SET status = 'PAID', paid_at = {sql_value(row['paid_at'])} WHERE id = {oid};")
            event_time = row['paid_at']
            lines.append(f"UPDATE order_status_histories SET changed_at = {sql_value(event_time)} WHERE order_id = {oid} AND new_status = 'PAID';")
        if row['status'] == 'REFUNDED':
            lines.append(f"UPDATE orders SET status = 'REFUNDED', refunded_at = {sql_value(row['refunded_at'])} WHERE id = {oid};")
            lines.append(f"UPDATE order_status_histories SET changed_at = {sql_value(row['refunded_at'])} WHERE order_id = {oid} AND new_status = 'REFUNDED';")
        if row['status'] == 'FAILED':
            lines.append(f"UPDATE orders SET status = 'FAILED' WHERE id = {oid};")
            event_time = row['created_at'] + timedelta(hours=1)
            lines.append(f"UPDATE order_status_histories SET changed_at = {sql_value(event_time)} WHERE order_id = {oid};")
    lines.extend(insert('ai_results', row) for row in data['ai_results'])
    for table in ['members', 'customers', 'orders', 'ai_results', 'order_status_histories']:
        lines.append(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), COALESCE(MAX(id), 1), COUNT(*) > 0) FROM {table};")
    lines.append('COMMIT;')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--customers', type=int, default=60)
    parser.add_argument('--days', type=int, default=30)
    parser.add_argument('--end-date', type=date.fromisoformat, default=date(2026, 11, 24))
    parser.add_argument('--seed', type=int, default=42)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    try:
        data = build_dataset(args.customers, args.days, args.end_date, args.seed)
    except ValueError as exc:
        parser.error(str(exc))
    sql = render_sql(data)
    if args.output:
        args.output.write_text(sql, encoding='utf-8')
        print(f"Đã tạo {args.output}: {len(data['customers'])} khách, "
              f"{len(data['orders'])} đơn, {len(data['ai_results'])} kết quả AI.")
    else:
        print(sql, end='')


if __name__ == '__main__':
    main()
